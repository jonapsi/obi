-- Permisos de audit_log: el usuario de la app solo puede leer e insertar.
-- Se aplica solo si el rol obi_app ya existe.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'obi_app') THEN
    REVOKE ALL ON "audit_log" FROM obi_app;
    GRANT SELECT, INSERT ON "audit_log" TO obi_app;
  ELSE
    RAISE NOTICE 'Rol obi_app no existe: crear el rol y volver a aplicar los permisos de audit_log';
  END IF;
END
$$;

